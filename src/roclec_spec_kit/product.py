"""Optional deterministic views over consumer-owned product sources."""

from pathlib import Path
import re

from .config import ConfigError, Project


def parse_source(path: Path) -> dict[str, str]:
    if not path.is_file():
        raise ConfigError(f"product source missing: {path}")
    body = re.sub(r"<!--.*?-->", "", path.read_text(encoding="utf-8"), flags=re.S)
    result = {}
    current = None
    lines = []
    for line in body.splitlines():
        heading = re.fullmatch(r"## (.+?)\s*", line)
        if heading:
            if current is not None:
                result[current] = "\n".join(lines).strip()
            current = heading[1]
            if current in result:
                raise ConfigError(f"duplicate product section {current}: {path}")
            lines = []
        elif current is not None:
            lines.append(line)
        elif line.strip() and not line.startswith("# "):
            raise ConfigError(f"product content before first section: {path}")
    if current is not None:
        result[current] = "\n".join(lines).strip()
    if not result or not any(result.values()):
        raise ConfigError(f"empty product source: {path}")
    return result


def product_views(project: Project) -> dict[Path, str]:
    views = {}
    for name, component in project.components.items():
        settings = component.product
        if settings is None:
            continue
        core = parse_source(project.root / settings["core"])
        own = parse_source(project.root / settings["source"])
        if {"Platform", "Stack"}.intersection(core):
            raise ConfigError("Platform and Stack belong in component product sources, not core")
        if not own.get("Platform") or not own.get("Stack"):
            raise ConfigError(f"{name}: product source requires Platform and Stack")
        headings = ["Platform", "Stack", *dict.fromkeys([*core, *own])]
        headings = list(dict.fromkeys(headings))
        lines = ["# Product", "", "<!-- impeccable:product-schema 1 -->",
                 f"<!-- Generated by roclec product from {settings['core']} + {settings['source']}. Do not edit. -->", ""]
        for heading in headings:
            content = "\n\n".join(part for part in (core.get(heading, ""), own.get(heading, "")) if part)
            if content:
                lines.extend(["## " + heading, "", content, ""])
        target = project.root / settings["output"]
        if target.exists() and "<!-- Generated by roclec product " not in target.read_text(encoding="utf-8"):
            raise ConfigError(f"refusing to overwrite unmanaged product view: {target}")
        views[target] = "\n".join(lines)
    return views


def product_errors(project: Project) -> list[str]:
    try:
        views = product_views(project)
    except ConfigError as exc:
        return [str(exc)]
    return [f"{path.relative_to(project.root)} is missing or stale (run roclec product --write)"
            for path, body in views.items() if not path.is_file() or path.read_text(encoding="utf-8") != body]
