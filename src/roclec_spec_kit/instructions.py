"""Managed instruction block of AGENTS.md/CLAUDE.md and its authority map (TK.4, D35).

The block keeps the routing text shipped in ``assets/project/agent-instructions.md`` and appends a
map of the agreed project authorities: links grouped by role and stage, never their content. It is
a pure function of the references, the stage ``skills`` of the flow and the profile components, so
`check` can compare it and `views --write`/`skills` can regenerate it. Text outside the block is
consumer-owned and preserved byte for byte. This module only renders and splits text.
"""
from __future__ import annotations

from importlib.resources import files

from .knowledge import SKILL_ROLE
from .model import ModelError, need

START, END = "<!-- roclec-spec-kit:begin -->", "<!-- roclec-spec-kit:end -->"
FILES = ("AGENTS.md", "CLAUDE.md")
HEADING = "### Authority map"
RULE = ("Generated by Roclec from `.roclec/references.json` and `.roclec/flow.toml`; regenerate it with "
        "`roclec views --write` or `roclec skills`, never by hand. Follow these agreed authorities. Do not create new "
        "conventions, references or skills without registering and agreeing them (`roclec reference add` and "
        "`roclec foundation agree`). Load a skill's content only when its stage needs it.")
EMPTY = ("No agreed authorities yet: register them with `roclec reference add` and agree them with "
         "`roclec foundation agree`.")


def routing():
    return files("roclec_spec_kit").joinpath("assets/project/agent-instructions.md").read_text(encoding="utf-8").strip()


def decode(content, name):
    """Text of an instruction file; UNMANAGED_FILE when it is not UTF-8."""
    try:
        return content.decode("utf-8")
    except UnicodeDecodeError as exc:
        raise ModelError("UNMANAGED_FILE", "Instruction file is not UTF-8 text", path=name) from exc


def split(body, name):
    """(before, block, after) of the one managed block, None without one; UNMANAGED_FILE when malformed."""
    need(body.count(START) == body.count(END) and body.count(START) <= 1
         and (START not in body or body.index(START) < body.index(END)),
         "UNMANAGED_FILE", "Malformed managed instruction block", path=name,
         remediation=f"Keep exactly one {START} line followed by one {END} line, then run `roclec skills`.")
    if START not in body:
        return None
    before, rest = body.split(START, 1)
    inner, after = rest.split(END, 1)
    return before, START + inner + END, after


def place(body, block, name):
    """`body` with its managed block replaced by `block`, or `block` appended when it has none."""
    parts = split(body, name)
    if parts is None:
        return body + ("\n\n" if body else "") + block + "\n"
    return parts[0] + block + parts[2]


def _target(path):
    return f"<{path}>" if any(c in path for c in " ()") else path


def authority_map(refs, skill_stages, every_stage, components):
    """Markdown lines of the map.

    `refs` are the registered references ({id: ref}); only those with a `decision_id` (agreed at least
    once) are listed, and ADRs another registered ADR supersedes are left out. Current validity is
    the gates' concern. `skill_stages` maps a skill to the stages where it applies, in flow order.
    """
    superseded = {old for ref in refs.values() if ref["role"] == "decision" for old in ref.get("supersedes", [])}
    agreed = [ref for _, ref in sorted(refs.items()) if ref["decision_id"] is not None]
    everything = sorted(components)

    def entry(ref, label):
        scope = "all components" if sorted(ref["components"]) == everything else ", ".join(sorted(ref["components"]))
        return f"- {label}`{ref['id']}`: [{ref['path']}]({_target(ref['path'])}); components: {scope}"

    roles = sorted((ref for ref in agreed if ref["role"] not in ("decision", SKILL_ROLE)),
                   key=lambda ref: (ref["role"], ref["id"]))
    adrs = [ref for ref in agreed if ref["role"] == "decision" and ref["id"] not in superseded]
    skills = [ref for ref in agreed if ref["role"] == SKILL_ROLE]
    lines = [HEADING, ""]
    if not (roles or adrs or skills):
        return lines + [EMPTY]
    lines += [RULE]
    if roles:
        lines += ["", "References by role:", *(entry(ref, f"{ref['role']} ") for ref in roles)]
    if adrs:
        lines += ["", "ADRs:", *(entry(ref, "") for ref in adrs)]
    if skills:
        lines += ["", "Knowledge skills (`.agents/skills/`, copied to `.claude/skills/` by `roclec skills`):"]
        for ref in skills:
            stages = skill_stages.get(ref["id"], every_stage)
            label = "every stage" if list(stages) == list(every_stage) else ", ".join(stages)
            lines.append(entry(ref, "") + f"; stages: {label}")
    return lines


def block(map_lines):
    """The managed block of the project root: routing text followed by the authority map."""
    return START + "\n" + routing() + "\n\n" + "\n".join(map_lines) + "\n" + END


def linked_block(project, name):
    """The managed block of a linked code repo: routing text and a pointer to the project root's map."""
    return (START + "\n" + routing() + "\n\n" + HEADING + "\n\nThis repo is linked to a Roclec project: follow the "
            f"authority map in the managed block of `{project}/{name}`.\n" + END)
